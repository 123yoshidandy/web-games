import { ARMS, ARM_TYPES } from './arms.js';

const stats = ARM_TYPES.map((type) => {
    const a = ARMS[type];
    const target = a.vsEarth && a.vsAir ? '地・空' : a.vsEarth ? '地上' : a.vsAir ? '空' : '—';
    return `<tr><td>${a.name}${a.onAir ? '（空）' : ''}</td><td>${a.cost}</td><td>${a.life}</td><td>${a.attack}</td><td>${a.range}</td><td>${a.bullets}</td><td>${target}</td></tr>`;
}).join('');

