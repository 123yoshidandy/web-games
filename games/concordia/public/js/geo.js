// 経度・緯度を、描く座標（左上が 0,0）に直す。経度は緯度 40 度での縮みを掛ける
export const SCALE = 20;
const SHRINK = Math.cos(40 * Math.PI / 180);
export function project([lon, lat]) {
    return [
        Math.round((lon - BOUNDS.west) * SHRINK * SCALE * 10) / 10,
        Math.round((BOUNDS.north - lat) * SCALE * 10) / 10
    ];
}
export const MAP_WIDTH = Math.round((BOUNDS.east - BOUNDS.west) * SHRINK * SCALE);
export const MAP_HEIGHT = Math.round((BOUNDS.north - BOUNDS.south) * SCALE);
