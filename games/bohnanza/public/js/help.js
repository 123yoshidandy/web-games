/**
 * 遊び方の文と、タイトル画面の絵
 */

import { BEANS, BEAN_TYPES } from './cards.js';
import { sym } from './art.js';

export function helpHtml() {
    const table = BEAN_TYPES.map(t => {
        const b = BEANS[t];
        return `<tr><th>${sym(t)}${b.name}</th><td>${b.count}</td>${b.steps.map(s => `<td>${s ?? '−'}</td>`).join('')}</tr>`;
    }).join('');
    return `
        <h3>目的</h3>
        <p>豆を畑に植えて育て、売って金を集めます。山が3回なくなったら終わり（3人は2回）。畑の豆を売り、金の多い人の勝ち（同点なら手札の多い人）。</p>
        <h3>手札の順番</h3>
        <p>手札の並びは変えられません。植えるのはいつも一番前（左）から、引いたカードは一番後ろ（右）に入ります。</p>
        <h3>手番の流れ</h3>
        <p><b>1. 植える</b>　手札の一番前を植えます。続けてもう1枚植えてもかまいません。</p>
        <p><b>2. 表にして取引</b>　山から2枚を表にします。手番の人は、表の2枚と手札を出して、ほかの人と交換したり、あげたりできます。ほかの人は手番の人とだけ、手札から取引できます。</p>
        <p><b>3. もらった豆を植える</b>　取引でもらった豆と、手番の人の残った表の豆は、全部植えます。</p>
        <p><b>4. 引く</b>　手番の人が山から3枚を、手札の後ろへ。</p>
        <h3>畑</h3>
        <p>畑は2つ（3人は最初から3つ）。1つの畑には1種類だけ。同じ種類の畑があればそこに、なければ空いた畑に植えます。植える畑がなければ、どれかの畑を売って空けます。3つ目の畑は3金で買えます（4〜5人）。</p>
        <h3>売る</h3>
        <p>畑の豆を全部売り、表の枚数に応じて金になります。いつでも売れます。1枚だけの畑は、ほかに2枚以上の畑があれば売れません。</p>
        <table class="htable"><thead><tr><th>豆</th><th>枚</th><th>1金</th><th>2金</th><th>3金</th><th>4金</th></tr></thead><tbody>${table}</tbody></table>
        <p class="note">3人はカカオ、4〜5人はコーヒーを使いません。</p>
        <h3>操作</h3>
        <p>光っている畑を押して植えます。畑の「売る」で売ります。取引は「提案」から、出すカードともらうものを選んで送ります。CPU からの提案は「受ける／断る」で答えます。上の人の欄を押すと、その人の畑が見られます。</p>`;
}

export function titleArtHtml() {
    return `<div class="t-scene">${['chili', 'blackEyed', 'blue', 'garden', 'coffee'].map((t, i) => `<span class="t-bean" style="--i:${i - 2}">${sym(t)}</span>`).join('')}</div>`;
}
