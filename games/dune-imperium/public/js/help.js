import { LEADERS } from './cards.js';

export function helpHtml() {
    return `
<h3>目的</h3>
<p>砂の惑星アラキスで、名家の当主として勢力と手を結び、紛争に勝って<b>10点</b>を目指します。だれかが10点以上になったラウンドの終わりか、10ラウンドで終わり、点の多い人の勝ち（同点はスパイス・ソラリ・水・駐屯地の部隊の順で比べます）。</p>
<h3>ラウンドの流れ</h3>
<ul>
<li>初めに<b>紛争</b>のカードを1枚めくり、全員が手札を5枚引きます</li>
<li>先手番から順に、1人ずつ<b>エージェントを送る</b>か<b>公開</b>をします。公開した人は、そのラウンドはもう番がありません</li>
<li>全員が公開したら<b>戦い</b>。紛争の褒美を分け、エージェントが戻り、先手番が隣へ移ります</li>
</ul>
<h3>エージェントを送る</h3>
<p>手札を1枚選び、カードに描かれた<b>印</b>と同じ印の、空いている場所に送ります。場所の費用を払い、場所とカードの効果を受けます。勢力（皇帝・ギルド・ベネ・ゲセリット・フレメン）の場所では、その勢力の<b>影響力</b>が1上がります。</p>
<p>剣の印の場所（<b>紛争の場所</b>）では、その番に得た部隊と、駐屯地の部隊を2つまで紛争に送れます。</p>
<h3>公開</h3>
<p>残りの手札をすべて公開し、<b>説得</b>の合計で列のカードや予備のカードを買います（買ったカードは捨て札へ）。<b>剣</b>は紛争の戦力に足されます。</p>
<h3>戦い</h3>
<p>戦力は、紛争にいる部隊1つにつき2と、剣の合計（部隊がいなければ0）。紛争に部隊がいる人は、順に<b>戦闘の陰謀カード</b>を使えます。1位と2位（4人なら3位も）が褒美を得ます。同点の1位は2位の褒美、同点の2位は3位の褒美になります。</p>
<h3>影響力と同盟</h3>
<p>影響力が<b>2</b>になると1点、<b>4</b>で勢力の褒美を1度だけ得ます。影響力4以上で一番の人がその勢力と<b>同盟</b>を結び、1点を得ます（追い越されると移ります）。</p>
<h3>主な場所</h3>
<ul>
<li><b>最高評議会</b>：ソラリ5。以後、公開のたびに説得+2</li>
<li><b>メンタート</b>：ソラリ2。カードを1枚引き、このラウンドだけエージェント+1</li>
<li><b>ソードマスター</b>：ソラリ8。3人目のエージェント</li>
<li><b>砂漠</b>（帝国盆地・ハッガ盆地・大平原）：スパイスを得る。だれも送らなかった砂漠には、ラウンドの終わりにスパイスが1たまります</li>
<li><b>メランジの売却</b>：スパイス2〜5をソラリ6〜12に換える</li>
</ul>
<h3>陰謀カード</h3>
<p><b>策略</b>は自分の番に、<b>戦闘</b>は戦いのときに使います。<b>終局</b>はゲームの終わりに条件を満たせば1点です。</p>
<h3>リーダー</h3>
<ul>${LEADERS.map(l => `<li><b>${l.name}</b>（${l.ability}）：${l.text}</li>`).join('')}</ul>
<h3>コツ</h3>
<p>序盤はカードを買ってデッキを強くし、評議会の席やソードマスターを早めに。中盤からは紛争と影響力で点を重ねましょう。</p>`;
}

